"""The website is a wiki for someone watching the simulation, not a render of docs/.

Owner decisions on #845 (#715 6789714730 and 6789779149): three spaces (World Knowledge, Technical,
Control Guide); World Knowledge fact pages are generated from repository data at build time and
never committed; docs/ is not rendered. Parsed as text, the way tests/static/test_deploy_docs_heap_limit.py
reads its workflow: website/node_modules is not installed in CI's Python jobs, so the config cannot be evaluated.
"""

import json
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent.parent
_WEBSITE = _ROOT / "website"
_CONFIG = (_WEBSITE / "docusaurus.config.js").read_text(encoding="utf-8")
_SIDEBARS = (_WEBSITE / "sidebars.js").read_text(encoding="utf-8")


def test_docs_folder_is_not_rendered():
    assert "path: '../docs'" not in _CONFIG
    assert "routeBasePath: 'docs'" not in _CONFIG
    assert "path: 'wiki'" in _CONFIG
    assert "routeBasePath: 'wiki'" in _CONFIG


def test_search_indexes_the_wiki_only():
    start = _CONFIG.index("docsRouteBasePath: [")
    block = _CONFIG[start:_CONFIG.index("]", start)]
    assert "'wiki'" in block
    assert "'docs'" not in block


def test_three_spaces_each_have_a_sidebar_a_navbar_tab_and_a_landing_page():
    for sidebar_id, folder in [("worldKnowledge", "world-knowledge"), ("technical", "technical"), ("controlGuide", "control-guide")]:
        assert f"{sidebar_id}: [{{ type: 'autogenerated', dirName: '{folder}' }}]" in _SIDEBARS
        assert f"sidebarId: '{sidebar_id}'" in _CONFIG
        assert (_WEBSITE / "wiki" / folder / "index.md").is_file()


def test_broken_links_fail_the_build():
    assert "onBrokenLinks: 'throw'" in _CONFIG
    assert "onBrokenMarkdownLinks: 'throw'" in _CONFIG


def test_generator_runs_before_build_and_start():
    scripts = json.loads((_WEBSITE / "package.json").read_text(encoding="utf-8"))["scripts"]
    assert scripts["generate"] == "python3 scripts/generate_wiki.py"
    assert scripts["prebuild"] == "npm run generate"
    assert scripts["prestart"] == "npm run generate"


def test_generated_folders_are_never_committed():
    ignored = (_WEBSITE / ".gitignore").read_text(encoding="utf-8").splitlines()
    for folder in ("laws", "mechanisms", "catalog", "glossary"):
        assert f"/wiki/world-knowledge/{folder}/" in ignored


def test_removed_sidebar_files_stay_deleted():
    for name in ("sidebars-archive.js", "sidebars-tickets.js", "sidebars-artifacts.js", "sidebars-agent-monitoring.js"):
        assert not (_WEBSITE / name).exists()


def test_homepage_links_the_three_spaces_and_no_docs_counts():
    text = (_WEBSITE / "src" / "pages" / "index.js").read_text(encoding="utf-8")
    for route in ("/wiki/world-knowledge", "/wiki/technical", "/wiki/control-guide"):
        assert route in text
    assert "/docs/" not in text
    assert "documents" not in text
